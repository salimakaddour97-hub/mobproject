
class Animal {
  final String name;
  final String emoji;
  final String image;
  final String sound;
  final String habitat;
  final String food;
  final String description;

  const Animal({
    required this.name,
    required this.emoji,
    required this.image,
    required this.sound,
    required this.habitat,
    required this.food,
    required this.description,
  });
}
